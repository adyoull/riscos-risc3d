#!/usr/bin/env python3
# gen.py OUTDIR: writes the RISC3D command stream's two ends from the
# Khronos header (include/GLES2/gl2.h):
#   r3d_ops.h      the opcodes (one per GLES 2 function, in the header's order)
#   client_gen.c   the library's functions that need no hand-written code
#   server_gen.c   the Linux helper's table of the driver's functions and
#                  its dispatch for the same commands
# A command is words: opcode, length in words (with these two), arguments.
# Functions with pointer arguments that fit no pattern here are written
# by hand at both ends (lib/r3d_gl.c, linux/rol-3d.c): HAND below.
#
# Copyright (c) 2026 Andrew Youll. MIT licence (see LICENSE).
import re, sys, os

here = os.path.dirname(os.path.abspath(__file__))
out = sys.argv[1]
src = open(os.path.join(here, '..', 'include', 'GLES2', 'gl2.h')).read()

HAND = {
    'glBindAttribLocation', 'glGetAttribLocation', 'glGetUniformLocation',
    'glShaderSource', 'glGetShaderInfoLog', 'glGetProgramInfoLog',
    'glGetShaderSource', 'glGetActiveAttrib', 'glGetActiveUniform',
    'glGetAttachedShaders', 'glGetShaderPrecisionFormat', 'glGetString',
    'glGetBooleanv', 'glGetFloatv', 'glGetIntegerv', 'glBufferData',
    'glBufferSubData', 'glTexImage2D', 'glTexSubImage2D',
    'glCompressedTexImage2D', 'glCompressedTexSubImage2D', 'glReadPixels',
    'glVertexAttribPointer', 'glDrawArrays', 'glDrawElements',
    'glGetVertexAttribPointerv', 'glShaderBinary', 'glBindFramebuffer',
}
# the library notes these before sending them (lib/r3d_gl.c: r3d_track_*)
TRACK = {'glBindBuffer', 'glEnableVertexAttribArray',
         'glDisableVertexAttribArray', 'glPixelStorei', 'glDeleteBuffers'}

funcs = []
for m in re.finditer(r'GL_APICALL\s+(.*?)\s*GL_APIENTRY\s+(gl\w+)\s*\((.*?)\);', src):
    ret, name, args = m.group(1).strip(), m.group(2), m.group(3).strip()
    al = []
    if args != 'void':
        for a in args.split(','):
            a = a.strip()
            mm = re.match(r'(.*?)(\w+)$', a)
            al.append((mm.group(1).strip(), mm.group(2)))
    funcs.append((ret, name, al))

def is_f(t): return t == 'GLfloat'
def is_ptr(t): return '*' in t

def kind(ret, name, al):
    if name in HAND:
        return 'hand'
    if not any(is_ptr(t) for t, _ in al):
        return 'auto'
    if re.match(r'glGen(Buffers|Textures|Framebuffers|Renderbuffers)$', name):
        return 'gen'
    if re.match(r'glDelete(Buffers|Textures|Framebuffers|Renderbuffers)$', name):
        return 'del'
    m = re.match(r'glUniform([1234])([fi])v$', name)
    if m:
        return ('uv', int(m.group(1)))
    m = re.match(r'glUniformMatrix([234])fv$', name)
    if m:
        return ('um', int(m.group(1)) ** 2)
    m = re.match(r'glVertexAttrib([1234])fv$', name)
    if m:
        return ('vv', int(m.group(1)))
    if name in ('glTexParameterfv', 'glTexParameteriv'):
        return ('vv', 1)
    # the last argument is where one value (or a few) comes back
    if is_ptr(al[-1][0]) and not any(is_ptr(t) for t, _ in al[:-1]) and name.startswith('glGet'):
        return 'out'
    raise SystemExit('no rule for ' + name)

FIRST = 16
ops = [(n, FIRST + i) for i, (_, n, _) in enumerate(funcs)]

with open(os.path.join(out, 'r3d_ops.h'), 'w') as f:
    f.write('/* Generated by proto/gen.py from GLES2/gl2.h: do not edit. */\n')
    f.write('#ifndef R3D_OPS_H\n#define R3D_OPS_H\n')
    f.write('#define R3D_PROTOCOL 1\n')
    f.write('enum {\n  OP_SURFACE = 1, OP_PRESENT, OP_CLIENT_ARRAY, OP_DRAW_ELEMENTS_INLINE,\n  OP_SYNC, OP_INFO,\n')
    for n, o in ops:
        f.write('  OP_%s = %d,\n' % (n, o))
    f.write('  OP_END\n};\n#endif\n')

def cargs(al): return ', '.join('%s %s' % (t, n) for t, n in al) or 'void'
def put(i, t, n):
    return '  a[%d] = %s;\n' % (i, 'r3d_f2u (%s)' % n if is_f(t) else '(uint32_t) %s' % n)
def get(i, t):
    return 'r3d_u2f (a[%d])' % i if is_f(t) else '(%s) a[%d]' % (t, i)

c = open(os.path.join(out, 'client_gen.c'), 'w')
s = open(os.path.join(out, 'server_gen.c'), 'w')
c.write('/* Generated by proto/gen.py from GLES2/gl2.h: do not edit. */\n')
s.write('/* Generated by proto/gen.py from GLES2/gl2.h: do not edit. */\n')
s.write('static struct gl_funcs {\n')
for ret, name, al in funcs:
    s.write('  %s (*%s) (%s);\n' % (ret, name[2:], cargs(al)))
s.write('} gl;\n')
s.write('static const char *const gl_names[] = {\n')
for ret, name, al in funcs:
    s.write('  "%s",\n' % name)
s.write('  0 };\n\n')
s.write('/* 1: done; 0: not one of these (hand-written) */\n')
s.write('static int\ndispatch_gen (uint32_t op, const uint32_t *a, uint32_t n)\n{\n  (void) n;\n  switch (op)\n    {\n')

for ret, name, al in funcs:
    k = kind(ret, name, al)
    if k == 'hand':
        continue
    op = 'OP_' + name
    track = '  r3d_track_%s (%s);\n' % (name, ', '.join(n for _, n in al)) if name in TRACK else ''
    c.write('\n%s\n%s (%s)\n{\n' % (ret, name, cargs(al)))
    if k == 'auto':
        c.write(track)
        if al:
            c.write('  uint32_t *a = r3d_put (%s, %d);\n' % (op, len(al)))
            c.write('  if (!a)\n    return%s;\n' % ('' if ret == 'void' else ' 0'))
        else:
            c.write('  r3d_put (%s, 0);\n' % op)
        for i, (t, n) in enumerate(al):
            c.write(put(i, t, n))
        call = 'gl.%s (%s)' % (name[2:], ', '.join(get(i, t) for i, (t, _) in enumerate(al)))
        if ret == 'void':
            s.write('    case %s:\n      %s;\n      return 1;\n' % (op, call))
        else:
            c.write('  uint32_t r = 0;\n  r3d_sync (&r, 4);\n  return (%s) r;\n' % ret)
            s.write('    case %s:\n      {\n\tuint32_t r = (uint32_t) %s;\n\treply (&r, 4);\n\treturn 1;\n      }\n' % (op, call))
    elif k == 'gen':
        c.write('  if (n <= 0)\n    return;\n')
        c.write('  uint32_t *a = r3d_put (%s, 1);\n  if (!a)\n    return;\n  a[0] = (uint32_t) n;\n' % op)
        c.write('  r3d_sync (%s, (size_t) n * 4);\n' % al[1][1])
        s.write('    case %s:\n      {\n\tGLuint *v = scratch (a[0] * 4);\n\tgl.%s ((GLsizei) a[0], v);\n\treply (v, a[0] * 4);\n\treturn 1;\n      }\n' % (op, name[2:]))
    elif k == 'del':
        c.write('  if (n <= 0)\n    return;\n')
        c.write(track)
        c.write('  uint32_t *a = r3d_put (%s, 1 + n);\n  if (!a)\n    return;\n  a[0] = (uint32_t) n;\n' % op)
        c.write('  memcpy (a + 1, %s, (size_t) n * 4);\n' % al[1][1])
        s.write('    case %s:\n      gl.%s ((GLsizei) a[0], (const GLuint *) (a + 1));\n      return 1;\n' % (op, name[2:]))
    elif k[0] in ('uv', 'um'):
        per = k[1]
        if k[0] == 'uv':
            c.write('  if (count <= 0)\n    return;\n')
            c.write('  uint32_t *a = r3d_put (%s, 2 + count * %d);\n  if (!a)\n    return;\n' % (op, per))
            c.write('  a[0] = (uint32_t) location;\n  a[1] = (uint32_t) count;\n  memcpy (a + 2, value, (size_t) count * %d);\n' % (per * 4))
            s.write('    case %s:\n      gl.%s ((GLint) a[0], (GLsizei) a[1], (const void *) (a + 2));\n      return 1;\n' % (op, name[2:]))
        else:
            c.write('  if (count <= 0)\n    return;\n')
            c.write('  uint32_t *a = r3d_put (%s, 3 + count * %d);\n  if (!a)\n    return;\n' % (op, per))
            c.write('  a[0] = (uint32_t) location;\n  a[1] = (uint32_t) count;\n  a[2] = transpose;\n  memcpy (a + 3, value, (size_t) count * %d);\n' % (per * 4))
            s.write('    case %s:\n      gl.%s ((GLint) a[0], (GLsizei) a[1], (GLboolean) a[2], (const GLfloat *) (a + 3));\n      return 1;\n' % (op, name[2:]))
    elif k[0] == 'vv':
        per = k[1]
        ns = len(al) - 1
        c.write('  uint32_t *a = r3d_put (%s, %d);\n  if (!a)\n    return;\n' % (op, ns + per))
        for i, (t, n) in enumerate(al[:-1]):
            c.write(put(i, t, n))
        c.write('  memcpy (a + %d, %s, %d);\n' % (ns, al[-1][1], per * 4))
        s.write('    case %s:\n      gl.%s (%s, (const void *) (a + %d));\n      return 1;\n' % (
            op, name[2:], ', '.join(get(i, t) for i, (t, _) in enumerate(al[:-1])), ns))
    elif k == 'out':
        ns = len(al) - 1
        c.write('  uint32_t *a = r3d_put (%s, %d);\n  if (!a)\n    return;\n' % (op, ns))
        for i, (t, n) in enumerate(al[:-1]):
            c.write(put(i, t, n))
        c.write('  uint32_t r[16];\n  memset (r, 0, sizeof r);\n  r3d_sync (r, sizeof r);\n')
        pn = [n for t, n in al[:-1] if n == 'pname']
        c.write('  memcpy (%s, r, 4 * r3d_values (%s));\n' % (al[-1][1], pn[0] if pn else '0'))
        s.write('    case %s:\n      {\n\tuint32_t r[16];\n\tmemset (r, 0, sizeof r);\n\tgl.%s (%s, (void *) r);\n\treply (r, sizeof r);\n\treturn 1;\n      }\n' % (
            op, name[2:], ', '.join(get(i, t) for i, (t, _) in enumerate(al[:-1]))))
    c.write('}\n')

s.write('    }\n  return 0;\n}\n')
# every forwarding function is r3d_glXxx (a program that also links Mesa
# has Mesa's own glXxx); Mesa's EGL builds a dispatch table from this list
c.write('\nconst struct r3d_gl_function r3d_gl_functions[] = {\n')
for ret, name, al in funcs:
    c.write('  { "%s", (void (*) (void)) %s },\n' % (name, name))
c.write('  { 0, 0 } };\n')
with open(os.path.join(out, 'r3d_gl_names.h'), 'w') as f:
    f.write('/* Generated by proto/gen.py from GLES2/gl2.h: do not edit.\n')
    f.write('   Include after <GLES2/gl2.h>: glXxx becomes RISC3D\'s r3d_glXxx. */\n')
    f.write('#ifndef R3D_GL_NAMES_H\n#define R3D_GL_NAMES_H\n')
    for ret, name, al in funcs:
        f.write('%s r3d_%s (%s);\n#define %s r3d_%s\n' % (ret, name, cargs(al), name, name))
    f.write('#endif\n')
c.close()
s.close()
print('%d functions, %d by hand' % (len(funcs), len(HAND)))
